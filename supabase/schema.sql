  ON time_entries(nsr) WHERE nsr IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_employee_account_email
  ON employees(lower(account_email))
  WHERE account_email IS NOT NULL AND account_email <> '';


CREATE TABLE IF NOT EXISTS admins (
  "user" TEXT PRIMARY KEY,
  salt TEXT,
  hash TEXT,
  role TEXT NOT NULL DEFAULT 'admin',
  department_id BIGINT,
  totp_secret TEXT,
  totp_enabled INTEGER NOT NULL DEFAULT 0
);
ALTER TABLE admins ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'admin';
ALTER TABLE admins ADD COLUMN IF NOT EXISTS department_id BIGINT;
ALTER TABLE admins ADD COLUMN IF NOT EXISTS totp_secret TEXT;
ALTER TABLE admins ADD COLUMN IF NOT EXISTS totp_enabled INTEGER NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  "user" TEXT,
  expires DOUBLE PRECISION,
  role TEXT NOT NULL DEFAULT 'admin',
  subject_id BIGINT
);
CREATE TABLE IF NOT EXISTS settings (
  k TEXT PRIMARY KEY,
  v TEXT
);
CREATE TABLE IF NOT EXISTS departments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  lead TEXT DEFAULT ''
);
CREATE TABLE IF NOT EXISTS employees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  cpf TEXT DEFAULT '',
  role TEXT DEFAULT '',
  salary DOUBLE PRECISION NOT NULL DEFAULT 0,
  benefits DOUBLE PRECISION NOT NULL DEFAULT 0,
  pin_salt TEXT,
  pin_hash TEXT,
  failed_pins INTEGER DEFAULT 0,
  active INTEGER DEFAULT 1,
  department_id BIGINT,
  account_email TEXT DEFAULT '',
  account_salt TEXT,
  account_hash TEXT
);
CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  material DOUBLE PRECISION DEFAULT 0,
  labor DOUBLE PRECISION DEFAULT 0,
  overhead DOUBLE PRECISION DEFAULT 0,
  price DOUBLE PRECISION DEFAULT 0
);
CREATE TABLE IF NOT EXISTS tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  assignee TEXT DEFAULT '',
  due TEXT DEFAULT '',
  status INTEGER DEFAULT 0,
  priority TEXT DEFAULT 'media',
  progress INTEGER DEFAULT 0,
  approval TEXT DEFAULT 'pendente',
  severity TEXT DEFAULT 'normal',
  department_id BIGINT,
  labor_budget_hours DOUBLE PRECISION DEFAULT 0,
  cost_ceiling DOUBLE PRECISION DEFAULT 0
);
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS department_id BIGINT;
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS labor_budget_hours DOUBLE PRECISION DEFAULT 0;
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS cost_ceiling DOUBLE PRECISION DEFAULT 0;
CREATE TABLE IF NOT EXISTS task_checklist (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  done INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS task_tags (
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  tag TEXT NOT NULL,
  PRIMARY KEY(task_id, tag)
);
CREATE TABLE IF NOT EXISTS task_attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  mime TEXT NOT NULL,
  size INTEGER NOT NULL,
  content TEXT NOT NULL,
  uploaded_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS task_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  details TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS time_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES employees(id),
  kind TEXT NOT NULL,
  at TEXT NOT NULL,
  lat DOUBLE PRECISION,
  lng DOUBLE PRECISION,
  distance_m DOUBLE PRECISION,
  accepted INTEGER NOT NULL,
  reason TEXT DEFAULT '',
  cpf TEXT DEFAULT '',
  nsr INTEGER,
  prev_hash TEXT,
  hash TEXT,
  samples INTEGER DEFAULT 1,
  spread_m DOUBLE PRECISION DEFAULT 0,
  task_id BIGINT REFERENCES tasks(id),
  labor_rate DOUBLE PRECISION
);
ALTER TABLE time_entries ADD COLUMN IF NOT EXISTS task_id BIGINT REFERENCES tasks(id);
ALTER TABLE time_entries ADD COLUMN IF NOT EXISTS labor_rate DOUBLE PRECISION;
CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL,
  description TEXT NOT NULL,
  amount DOUBLE PRECISION NOT NULL,
  due TEXT NOT NULL,
  paid INTEGER DEFAULT 0,
  paid_at TEXT,
  department_id BIGINT REFERENCES departments(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  unit TEXT DEFAULT 'un',
  stock DOUBLE PRECISION NOT NULL DEFAULT 0,
  unit_cost DOUBLE PRECISION NOT NULL DEFAULT 0,
  minimum_stock DOUBLE PRECISION NOT NULL DEFAULT 0
);
ALTER TABLE materials ADD COLUMN IF NOT EXISTS minimum_stock DOUBLE PRECISION NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS task_materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  material_id BIGINT NOT NULL REFERENCES materials(id),
  quantity DOUBLE PRECISION NOT NULL,
  consumed_quantity DOUBLE PRECISION NOT NULL DEFAULT 0,
  unit_cost DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS spaces (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  kind TEXT DEFAULT 'gestao',
  admin_email TEXT DEFAULT ''
);
CREATE TABLE IF NOT EXISTS space_bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  space_id BIGINT NOT NULL REFERENCES spaces(id) ON DELETE CASCADE,
  department_id BIGINT REFERENCES departments(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  starts_at TEXT NOT NULL,
  ends_at TEXT NOT NULL,
  booked_by TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS automation_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  trigger TEXT NOT NULL,
  threshold DOUBLE PRECISION DEFAULT 0,
  active INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS automation_runs (
  rule_id BIGINT NOT NULL REFERENCES automation_rules(id) ON DELETE CASCADE,
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  PRIMARY KEY(rule_id, task_id)
);
CREATE TABLE IF NOT EXISTS cost_analyses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  revenue DOUBLE PRECISION NOT NULL DEFAULT 0,
  material DOUBLE PRECISION NOT NULL DEFAULT 0,
  opex DOUBLE PRECISION NOT NULL DEFAULT 0,
  tax DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS integrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  kind TEXT NOT NULL,
  endpoint TEXT DEFAULT '',
  active INTEGER DEFAULT 1
);
CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at TEXT NOT NULL,
  actor TEXT NOT NULL DEFAULT '',
  role TEXT NOT NULL DEFAULT '',
  action TEXT NOT NULL,
  resource TEXT NOT NULL,
  status INTEGER NOT NULL,
  ip TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS notification_channels (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL,
  recipient TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope TEXT NOT NULL CHECK (scope IN ('team', 'private')),
  employee_id BIGINT REFERENCES employees(id) ON DELETE CASCADE,
  sender_role TEXT NOT NULL CHECK (sender_role IN ('admin', 'employee')),
  sender_employee_id BIGINT REFERENCES employees(id) ON DELETE SET NULL,
  sender_name TEXT NOT NULL,
  body TEXT NOT NULL,
  created_at TEXT NOT NULL
);
